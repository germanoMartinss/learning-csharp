// Igual
int x = 10;
int y = 10;

if (x == y)
{
    Console.WriteLine($"{x} é igual a {y}");
}

// Não igual
string player1 = "Germano";
string player2 = "Mauricio";

if (player1 != player2)
{
    Console.WriteLine($"{player1} é diferente de {player2}");
}

// Maior que 
int age1 = 30;
int age2 = 20;

if (age1 > age2)
{
    Console.WriteLine($"{age1} é maior que {age2}");
}

// Maior ou igual que
if (age1 >= age2)
{
    Console.WriteLine($"{age1} anos é MAIOR ou IGUAL a {age2} anos");
}

// Menor e menor que
if (age1 < age2)
{
    Console.WriteLine($"{age1} anos é MENOR que {age2} anos");
}

bool condition = x == y;

if (condition)
{
    Console.WriteLine("x é igual a y");
}
else
{
    Console.WriteLine("x não é igual a y");
}

